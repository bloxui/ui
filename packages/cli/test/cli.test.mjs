/**
 * End-to-end: runs the real CLI against the committed registry in scratch projects,
 * then type-checks what it installed.
 */

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { after, before, describe, test } from "node:test";
import { fileURLToPath } from "node:url";
import { addThemeImport, detectPackageManager, parseLooseJson, relativeImport } from "../src/project.mjs";
import { parseArgs } from "../src/cli.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../../..");
const bin = join(here, "../bin/blox.mjs");
const registry = join(repo, "apps/www/public/r");
// Inside packages/ui so TypeScript finds the packages the components import.
const scratchRoot = join(repo, "packages/ui/.cli-e2e");
const tsc = join(repo, "packages/ui/node_modules/typescript/bin/tsc");

function blox(cwd, ...args) {
  const result = spawnSync(process.execPath, [bin, ...args, "--registry", registry, "--no-install"], {
    cwd,
    encoding: "utf8",
  });
  return { code: result.status, output: `${result.stdout}${result.stderr}` };
}

function typecheck(cwd) {
  const result = spawnSync(process.execPath, [tsc, "-p", cwd], { encoding: "utf8" });
  return { code: result.status, output: `${result.stdout}${result.stderr}` };
}

const compilerOptions = {
  target: "ES2022",
  lib: ["dom", "dom.iterable", "ES2022"],
  module: "ESNext",
  moduleResolution: "Bundler",
  jsx: "react-jsx",
  strict: true,
  noUncheckedIndexedAccess: true,
  skipLibCheck: true,
  noEmit: true,
};

async function createProject(name, { src, alias }) {
  const cwd = join(scratchRoot, name);
  const base = src ? "src/" : "";
  await mkdir(join(cwd, `${base}app`), { recursive: true });
  await writeFile(join(cwd, "package.json"), JSON.stringify({ name, private: true }));
  await writeFile(join(cwd, "pnpm-lock.yaml"), "lockfileVersion: '9.0'\n");
  await writeFile(
    join(cwd, "tsconfig.json"),
    // Comments and a trailing comma, like a real Next.js tsconfig.
    `{
  // generated by a framework
  "compilerOptions": ${JSON.stringify(
    alias ? { ...compilerOptions, paths: { "@/*": [src ? "./src/*" : "./*"] } } : compilerOptions,
  )},
  "include": ["**/*.ts", "**/*.tsx"],
}
`,
  );
  await writeFile(join(cwd, `${base}app/globals.css`), '@import "tailwindcss";\n\nbody { margin: 0; }\n');
  return cwd;
}

before(() => rm(scratchRoot, { recursive: true, force: true }));
after(() => rm(scratchRoot, { recursive: true, force: true }));

describe("blox in a Next.js project with src/ and an @ alias", () => {
  let cwd;
  before(async () => {
    cwd = await createProject("with-alias", { src: true, alias: true });
  });

  test("init writes the config, theme and cn helper, and imports the theme", async () => {
    const { code, output } = blox(cwd, "init");
    assert.equal(code, 0, output);

    const config = JSON.parse(await readFile(join(cwd, "blox.json"), "utf8"));
    assert.deepEqual(config.aliases, { ui: "@/components/ui", lib: "@/lib", blocks: "@/components/blocks" });
    assert.equal(config.dirs.ui, "src/components/ui");
    assert.equal(config.css, "src/app/globals.css");

    assert.ok(existsSync(join(cwd, "src/styles/blox.css")));
    assert.ok(existsSync(join(cwd, "src/lib/cn.ts")));
    const css = await readFile(join(cwd, "src/app/globals.css"), "utf8");
    assert.match(css, /@import "tailwindcss";\n@import "\.\.\/styles\/blox\.css";/);
    assert.match(output, /pnpm add clsx@\^2\.1\.1 tailwind-merge@\^3\.0\.0/);
  });

  test("init refuses to run twice", () => {
    const { code, output } = blox(cwd, "init");
    assert.equal(code, 1);
    assert.match(output, /blox\.json already exists/);
  });

  test("add installs a component with everything it needs, using the alias", async () => {
    const { code, output } = blox(cwd, "add", "data-table");
    assert.equal(code, 0, output);
    for (const file of ["data-table", "table", "pagination", "checkbox", "input", "button", "spinner"]) {
      assert.ok(existsSync(join(cwd, `src/components/ui/${file}.tsx`)), `${file}.tsx is missing`);
    }
    const source = await readFile(join(cwd, "src/components/ui/data-table.tsx"), "utf8");
    assert.match(source, /from "@\/lib\/cn"/);
    assert.match(source, /from "@\/components\/ui\/checkbox"/);
    assert.doesNotMatch(source, /~ui|~lib/);
    assert.match(output, /radix-ui@/);
    assert.match(output, /created +src\/components\/ui\/table\.tsx/);
  });

  test("add only asks for packages the project does not already have", async () => {
    const pkgPath = join(cwd, "package.json");
    const pkg = JSON.parse(await readFile(pkgPath, "utf8"));
    await writeFile(pkgPath, JSON.stringify({ ...pkg, dependencies: { "radix-ui": "^1.0.0", clsx: "^2.0.0" } }));
    const { output } = blox(cwd, "add", "dialog", "--overwrite");
    assert.doesNotMatch(output, /radix-ui@|clsx@/);
    assert.match(output, /tailwind-merge@/);
  });

  test("add leaves files the user changed, and replaces them with --overwrite", async () => {
    const path = join(cwd, "src/components/ui/button.tsx");
    const original = await readFile(path, "utf8");
    await writeFile(path, `${original}\n// my change\n`);

    let result = blox(cwd, "add", "button");
    assert.match(result.output, /skipped/);
    assert.match(await readFile(path, "utf8"), /my change/);

    result = blox(cwd, "add", "button", "--overwrite");
    assert.equal(result.code, 0, result.output);
    assert.match(result.output, /replaced +src\/components\/ui\/button\.tsx/);
    assert.doesNotMatch(await readFile(path, "utf8"), /my change/);
  });

  test("--dry-run writes nothing", () => {
    const { code, output } = blox(cwd, "add", "calendar", "--dry-run");
    assert.equal(code, 0, output);
    assert.match(output, /would create/);
    assert.ok(!existsSync(join(cwd, "src/components/ui/calendar.tsx")));
  });

  test("add a block puts it in components/blocks", async () => {
    const { code, output } = blox(cwd, "add", "block-login");
    assert.equal(code, 0, output);
    const source = await readFile(join(cwd, "src/components/blocks/login.tsx"), "utf8");
    assert.match(source, /from "@\/components\/ui\/field"/);
  });

  test("everything installed type-checks", { timeout: 120_000 }, () => {
    blox(cwd, "add", "--all");
    const { code, output } = typecheck(cwd);
    assert.equal(code, 0, output);
  });

  test("unknown names fail with a helpful message", () => {
    const { code, output } = blox(cwd, "add", "buton");
    assert.equal(code, 1);
    assert.match(output, /"buton" is not in the registry/);
  });
});

describe("blox in a project without src/ or an alias", () => {
  test("writes relative imports that type-check", { timeout: 120_000 }, async () => {
    const cwd = await createProject("no-alias", { src: false, alias: false });
    let result = blox(cwd, "init");
    assert.equal(result.code, 0, result.output);
    assert.match(result.output, /imports will be relative/);

    result = blox(cwd, "add", "command", "block-settings");
    assert.equal(result.code, 0, result.output);

    const command = await readFile(join(cwd, "components/ui/command.tsx"), "utf8");
    assert.match(command, /from "\.\.\/\.\.\/lib\/cn"/);
    assert.match(command, /from "\.\/dialog"/);
    const block = await readFile(join(cwd, "components/blocks/settings.tsx"), "utf8");
    assert.match(block, /from "\.\.\/ui\/tabs"/);

    const check = typecheck(cwd);
    assert.equal(check.code, 0, check.output);
  });
});

describe("helpers", () => {
  test("parseArgs reads commands, names and flags", () => {
    assert.deepEqual(parseArgs(["add", "button", "dialog", "--overwrite", "--no-install", "--registry", "./r"]), {
      _: ["add", "button", "dialog"],
      install: false,
      overwrite: true,
      registry: "./r",
    });
    assert.throws(() => parseArgs(["add", "--registry"]), /needs a value/);
    assert.throws(() => parseArgs(["add", "--frobnicate"]), /Unknown option/);
  });

  test("parseLooseJson accepts comments and trailing commas but keeps strings intact", () => {
    assert.deepEqual(parseLooseJson('{ /* a */ "url": "http://x//y", // b\n "list": [1, 2,], }'), {
      url: "http://x//y",
      list: [1, 2],
    });
  });

  test("relativeImport always starts with a dot and uses forward slashes", () => {
    assert.equal(relativeImport("components/ui", "lib"), "../../lib");
    assert.equal(relativeImport("components/ui", "components/ui"), ".");
    assert.equal(relativeImport("app", "app/styles"), "./styles");
  });

  test("addThemeImport goes right after Tailwind, once", () => {
    const first = addThemeImport('@import "tailwindcss";\nbody {}\n', "./blox.css");
    assert.equal(first.css, '@import "tailwindcss";\n@import "./blox.css";\nbody {}\n');
    assert.equal(addThemeImport(first.css, "./blox.css").changed, false);
    assert.equal(addThemeImport("body {}", "./blox.css").reason, 'no @import "tailwindcss" found');
  });

  test("detectPackageManager reads the lockfile", async () => {
    const cwd = join(scratchRoot, "pm");
    await mkdir(cwd, { recursive: true });
    await writeFile(join(cwd, "yarn.lock"), "");
    assert.equal(detectPackageManager(cwd), "yarn");
  });
});
